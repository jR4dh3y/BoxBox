//! Generates, so the native app cannot drift from the web app:
//! - the colour tokens, from the `@theme` block of `frontend/src/routes/layout.css`;
//! - the embedded icon table, from what `scripts/extract-icons.ts` wrote to `assets/icons`.

use std::{env, fs, path::Path};

const CSS: &str = "../../frontend/src/routes/layout.css";

fn main() {
    println!("cargo:rerun-if-changed={CSS}");
    let css = fs::read_to_string(CSS).expect("read frontend/src/routes/layout.css");
    let after = css
        .split_once("@theme {")
        .map(|(_, rest)| rest)
        .expect("layout.css has an @theme block");
    // Later rules redefine some tokens (wallpaper mode); only the block counts.
    let mut depth = 1;
    let end = after
        .char_indices()
        .find(|&(_, ch)| {
            depth += match ch {
                '{' => 1,
                '}' => -1,
                _ => 0,
            };
            depth == 0
        })
        .map(|(index, _)| index)
        .expect("the @theme block is closed");
    let theme = &after[..end];
    let mut out = String::from("// Generated by build.rs from frontend/src/routes/layout.css.\n");
    let mut count = 0;
    for line in theme.lines() {
        let line = line.trim();
        let Some(rest) = line.strip_prefix("--color-") else { continue };
        let Some((name, value)) = rest.split_once(':') else { continue };
        let value = value.trim().trim_end_matches(';').trim();
        let hex = parse_hex(value).unwrap_or_else(|| panic!("--color-{name} is not a hex colour: {value}"));
        let ident = name.to_uppercase().replace('-', "_");
        out += &format!("/// `--color-{name}: {value}`\n#[allow(dead_code)]\npub const {ident}: u32 = 0x{hex:06x};\n");
        count += 1;
    }
    assert!(count > 0, "no --color-* tokens in layout.css");
    let out_dir = env::var("OUT_DIR").unwrap();
    fs::write(Path::new(&out_dir).join("tokens.rs"), out).unwrap();
    icons(Path::new(&out_dir));
}

fn icons(out_dir: &Path) {
    println!("cargo:rerun-if-changed=assets/icons");
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("assets/icons");
    let mut names: Vec<String> = fs::read_dir(&dir)
        .expect("read assets/icons")
        .filter_map(|entry| entry.ok()?.file_name().into_string().ok())
        .filter_map(|name| name.strip_suffix(".svg").map(str::to_string))
        .collect();
    names.sort();
    let mut out = String::from("// Generated by build.rs from assets/icons.\nconst ICONS: &[(&str, &[u8])] = &[\n");
    for name in &names {
        for variant in ["", "thin/"] {
            let file = dir.join(format!("{variant}{name}.svg"));
            out += &format!("    (\"icons/{variant}{name}.svg\", include_bytes!({:?})),\n", file.display().to_string());
        }
    }
    out += "];\n";
    fs::write(out_dir.join("icons.rs"), out).unwrap();
}

/// `#rgb` or `#rrggbb`.
fn parse_hex(value: &str) -> Option<u32> {
    let digits = value.strip_prefix('#')?;
    let full: String = match digits.len() {
        3 => digits.chars().flat_map(|c| [c, c]).collect(),
        6 => digits.to_string(),
        _ => return None,
    };
    u32::from_str_radix(&full, 16).ok()
}
